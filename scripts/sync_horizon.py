#!/usr/bin/env python3
"""Keep crates/rusticmc-server (its own Cargo workspace) in step with the pinned Horizon.

`rusticmc-server` depends on `horizon-client` by path. Cargo ignores `[patch]` sections outside the
root workspace, and Horizon pins patched crates (wgpu-hal, naga, libmimalloc-sys) and exact
versions in its Cargo.lock. So this script:

1. rewrites the `[patch.crates-io]` block of crates/rusticmc-server/Cargo.toml (between the
   `# BEGIN horizon-patch` / `# END horizon-patch` markers) from horizon/Cargo.toml, with paths
   made relative to the server crate;
2. seeds crates/rusticmc-server/Cargo.lock from horizon/Cargo.lock when it is missing (or with
   --reset-lock), so Horizon's dependencies keep Horizon's versions; cargo then only adds ours;
3. copies Horizon's `rust-version` requirement into a check.

  python3 scripts/sync_horizon.py            # update
  python3 scripts/sync_horizon.py --check    # CI: fail if out of date
  python3 scripts/sync_horizon.py --reset-lock
"""
from __future__ import annotations

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HORIZON = ROOT / "horizon"
SERVER = ROOT / "crates" / "rusticmc-server"
BEGIN, END = "# BEGIN horizon-patch", "# END horizon-patch"


def horizon_patch_block() -> str:
    text = (HORIZON / "Cargo.toml").read_text(encoding="utf-8")
    match = re.search(r"^\[patch\.crates-io\]\n(.*?)(?=^\[|\Z)", text, re.S | re.M)
    if not match:
        return ""
    lines = []
    for line in match.group(1).splitlines():
        if line.strip().startswith("#") or not line.strip():
            continue
        # path = "third_party/x"  ->  path = "../../horizon/third_party/x"
        line = re.sub(r'path\s*=\s*"([^"]+)"', lambda m: f'path = "../../horizon/{m.group(1)}"', line)
        lines.append(line)
    return "[patch.crates-io]\n" + "\n".join(lines) + "\n"


def rendered(manifest: str) -> str:
    block = f"{BEGIN}\n# Generated by scripts/sync_horizon.py from horizon/Cargo.toml: do not edit.\n{horizon_patch_block()}{END}"
    if BEGIN in manifest:
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, manifest, flags=re.S)
    return manifest.rstrip() + "\n\n" + block + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--reset-lock", action="store_true")
    args = parser.parse_args()

    manifest_path = SERVER / "Cargo.toml"
    if not manifest_path.exists():
        sys.exit(f"{manifest_path} is missing")
    current = manifest_path.read_text(encoding="utf-8")
    wanted = rendered(current)
    lock = SERVER / "Cargo.lock"

    if args.check:
        problems = []
        if current != wanted:
            problems.append("Cargo.toml [patch] block differs from horizon/Cargo.toml")
        if not lock.exists():
            problems.append("Cargo.lock missing")
        if problems:
            sys.exit("out of date (run scripts/sync_horizon.py): " + "; ".join(problems))
        print("rusticmc-server is in step with horizon/")
        return

    if current != wanted:
        manifest_path.write_text(wanted, encoding="utf-8")
        print("updated [patch] block")
    if args.reset_lock or not lock.exists():
        shutil.copyfile(HORIZON / "Cargo.lock", lock)
        print("seeded Cargo.lock from horizon/Cargo.lock")


if __name__ == "__main__":
    main()
